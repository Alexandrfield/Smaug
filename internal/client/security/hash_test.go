func TestHash(t *testing.T) {
	password := []byte{0xff, 0x00, 0xaa, 0x22}
	expected := []byte{
		0x52, 0x2e, 0x2d, 0x2b, 0xcf, 0x8e, 0xd7, 0x67, 0x6e, 0xd9, 0x24, 0x8a, 0xd2, 0x76, 0x63, 0x3e,
		0x27, 0xa1, 0x4d, 0x95, 0xfe, 0xbe, 0xaf, 0x34, 0x1f, 0xf2, 0xab, 0x1c, 0x16, 0x0c, 0x47, 0x1b,
	}
	actual := HashInputPassword(password)
	assert.ElementsMatch(t, actual, expected)
}

