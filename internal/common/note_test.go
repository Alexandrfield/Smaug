func TestGetDataForSign(t *testing.T) {

	info := []byte{0x01, 0xff, 0xab}
	temporyKey := []byte{0x01, 0xff, 0xab, 0xff, 0xff}
	cipherText := []byte{0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00}
	expected := []byte{0x01, 0xff, 0xab, 0x01, 0xff, 0xab, 0xff, 0xff, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00}
	note := CreatNote(info, temporyKey, cipherText)
	actual := note.GetDataForSign()
	assert.ElementsMatch(t, actual, expected)
}

