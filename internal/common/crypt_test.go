func TestEncryptDecryptAES(t *testing.T) {
	dataForSafe := []byte{0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff}
	key := []byte{0xb3, 0x0b, 0x25, 0x18, 0x4b, 0xb2, 0x89, 0xb3, 0x0b, 0x25, 0x18, 0x4b, 0xb2, 0x89, 0xff, 0xa4}
	cypherText, err := EncryptAES(dataForSafe, key)
	require.NoError(t, err)
	if bytes.Equal(cypherText, dataForSafe) {
		t.Errorf("not encrypt")
	}
	plainText, err := DecryptAES(cypherText, key)
	require.NoError(t, err)
	assert.ElementsMatch(t, dataForSafe, plainText)
}
